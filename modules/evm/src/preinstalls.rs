//! Canonical EVM preinstalled contracts.
//!
//! Foundry, Hardhat, Safe, and most ERC-4337/multicall tooling assume a
//! set of well-known contracts exist at fixed addresses on every EVM
//! chain. Without them, `forge create`/`create2` scripts, multicall
//! batching, and Permit2 approvals fail on first contact.
//!
//! Each entry is `(address, nonce, runtime code)` verified byte-for-byte
//! against Ethereum mainnet (`eth_getCode … "latest"`). The CREATE2
//! factory is the EIP-7997 canonical predeploy; the singleton factories
//! are the keyless-deployed proxies every tooling stack knows; Multicall3
//! and Permit2 are the same contracts Uniswap's deployer placed on every
//! major chain.
//!
//! Preinstalls are inserted via [`EvmModule::genesis_insert_account`]
//! during genesis application — they are ordinary accounts with nonce 1
//! (keyless-deployed contracts always carry nonce 1 so their CREATE'd
//! address stays reproducible) and zero balance.

use primitives::Address;
use revm::primitives::hardfork::SpecId;

/// A single preinstalled contract: fixed address + runtime bytecode.
pub struct Preinstall {
    /// Human-readable name (devlog/RPC debugging only).
    pub name: &'static str,
    /// Canonical deployment address — same on every EVM chain.
    pub address: &'static str,
    /// Account nonce at genesis. Keyless-deployed contracts use nonce 1
    /// so `CREATE`/`CREATE2` derivations match other chains.
    pub nonce: u64,
    /// Runtime bytecode (hex, no `0x` prefix), verified against mainnet.
    pub code: &'static str,
    /// Earliest hardfork that carries this contract, or `None` for
    /// fork-independent preinstalls. Fork-gated contracts (e.g. the
    /// EIP-2935 history contract exists only on Prague+) must not be
    /// installed under an earlier spec — a Cancun genesis carrying
    /// the contract would diverge from the real fork's genesis state
    /// root.
    pub requires_spec: Option<SpecId>,
}

