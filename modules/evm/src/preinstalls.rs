/// Decode a preinstall's hex address into a [`primitives::Address`].
///
/// # Panics
///
/// Panics if the table's address hex is malformed — a bug, not a
/// runtime condition (the table is compile-time fixed).
pub fn preinstall_address(p: &Preinstall) -> Address {
    let mut out = [0u8; 20];
    // The table is compile-time fixed; a malformed entry is a bug,
    // not a runtime condition — fail loudly at startup.
    alloy_primitives::hex::decode_to_slice(p.address, &mut out)
        .unwrap_or_else(|e| panic!("preinstall {} has bad address hex: {e}", p.name));
    Address(out)
}

/// Decode a preinstall's hex runtime code.
///
/// # Panics
///
/// Panics if the table's code hex is malformed — a bug, not a
/// runtime condition (the table is compile-time fixed).
pub fn preinstall_code(p: &Preinstall) -> Vec<u8> {
    alloy_primitives::hex::decode(p.code)
        .unwrap_or_else(|e| panic!("preinstall {} has bad code hex: {e}", p.name))
}
