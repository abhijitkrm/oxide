//! Corpus-replay bench: drives [`trading::MatchingEngine`] with the
//! shared matcher W1–W5 command corpora (`matcher-rust/spec/BENCH.md`)
//! so Oxide and matcher-rust are measured on identical command streams.
//!
//! ```text
//! corpus <prefix> [--fold] [--block N] [--reps R] [--latency] [--sink vec|count] [--replace cancel|native] [--batch]
//! ```
//!
//! Loads `<prefix>.setup.cmd.jsonl` (untimed) and `<prefix>.run.cmd.jsonl`
//! (measured). Prints one markdown row: best / median ops/s and the
//! median ns/op, or exact p50/p99/p99.9 with `--latency`.
//!
//! ## How the corpus maps onto the engine
//!
//! - Corpus prices are integer ticks around `MID`; they map onto a
//!   band of `MID ± BAND_TICKS` ticks at tick = 1e6 raw, qty onto
//!   lots of 1e3 raw. The band (10 401 levels) is far below the dense
//!   ladder cap (2^18).
//! - Oxide assigns order ids itself (sequentially, one per `place`
//!   call), while the corpus names orders by its own ids. A resolve
//!   pass (untimed) runs the corpus once through a scratch engine to
//!   learn each command's engine id; the timed pass then replays
//!   fully resolved [`Op`]s with no id translation in the loop, so
//!   the number is the engine and nothing else. The engine is
//!   deterministic, so the ids are identical on every replay.
//! - Oxide has no native replace (before step 4 of the matcher-parity
//!   plan): `Replace` is `cancel` + `place` (loses time priority even
//!   for a quantity decrease — the matcher keeps it). Both calls are
//!   inside the timed loop and count as ONE op, like the matcher.
//! - `--fold` enables the resting fold with the exchange module's real
//!   leaf. A block boundary is simulated every `--block N` ops (default
//!   1024): the bench calls `settle_fold()` then reads `resting_fold()` (what
//!   `state_root` does), as a block's end would (settle first, so the read is O(1)).
//!
//! Single-threaded, release build; fills go to a reused `Vec`.
#![allow(missing_docs)]
// Bench tooling: corpus numbers are small, bounded, and parsed from a
// trusted file generated by vectorgen; casts between i64/u64/usize are
// exact for every value it emits.
#![allow(
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::cast_precision_loss,
    clippy::cast_possible_wrap,
    clippy::inline_always,
    clippy::too_many_lines
)]

use primitives::Address;
use primitives::fixed::{Price, Qty};
use std::hint::black_box;
use std::time::Instant;
use trading::{
    DenseBook, FillSink, MarketConfig, MatchingEngine, NewOrder, OrderId, OrderOutcome, OrderType,
    Side, StpMode, TimeInForce,
};

/// Corpus mid price (vectorgen `MID`).
const MID: i64 = 500_000;
/// Half-width of the engine band in ticks (corpus spans MID ± 5 000).
const BAND_TICKS: i64 = 5_200;
const TICK: u64 = 1_000_000;
const LOT: u64 = 1_000;
const MIN_PRICE: u64 = 1_000_000_000;

#[derive(Clone, Copy)]
enum Op {
    Place(NewOrder),
    Cancel(OrderId),
    Replace(OrderId, NewOrder),
    /// Native amend (`--replace native`): same id, priority kept on a same-price decrease.
    Amend(OrderId, Price, Qty),
}

fn get<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let pat = format!("\"{key}\":");
    let start = line.find(&pat)? + pat.len();
    let rest = &line[start..];
    if let Some(q) = rest.strip_prefix('"') {
        Some(&q[..q.find('"')?])
    } else {
        Some(rest[..rest.find([',', '}']).unwrap_or(rest.len())].trim())
    }
}

enum Cmd {
    New { id: u64, order: NewOrder },
    Cancel { id: u64 },
    Replace { id: u64, price: i64, qty: u64 },
}

fn to_price(t: i64) -> Price {
    Price(MIN_PRICE + ((t - (MID - BAND_TICKS)) as u64) * TICK)
}

fn parse(line: &str) -> Cmd {
    let n = |k| get(line, k).unwrap().parse::<i64>().unwrap();
    match get(line, "cmd").unwrap() {
        "new" => {
            let id = n("order_id") as u64;
            let side = if get(line, "side") == Some("bid") { Side::Buy } else { Side::Sell };
            let (otype, tif) = match (get(line, "otype"), get(line, "tif")) {
                (Some("market"), _) => (OrderType::Market, TimeInForce::Ioc),
                (_, Some("post_only")) => (OrderType::PostOnly, TimeInForce::Gtc),
                (_, Some("ioc")) => (OrderType::Limit, TimeInForce::Ioc),
                (_, Some("fok")) => (OrderType::Limit, TimeInForce::Fok),
                _ => (OrderType::Limit, TimeInForce::Gtc),
            };
            let price = if otype == OrderType::Market { Price(0) } else { to_price(n("price")) };
            Cmd::New {
                id,
                order: NewOrder {
                    side,
                    order_type: otype,
                    tif,
                    price,
                    qty: Qty(n("qty") as u64 * LOT),
                    owner: Address([(id % 251) as u8 + 1; 20]),
                    stp: StpMode::None,
                },
            }
        }
        "cancel" => Cmd::Cancel { id: n("order_id") as u64 },
        _ => Cmd::Replace { id: n("order_id") as u64, price: n("price"), qty: n("qty") as u64 },
    }
}

fn load(path: &str) -> (usize, Vec<Cmd>) {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}"));
    let mut lines = text.lines();
    let max_orders = get(lines.next().unwrap(), "max_orders").unwrap().parse().unwrap();
    (max_orders, lines.filter(|l| !l.trim().is_empty()).map(parse).collect())
}

fn make_engine(max_orders: usize, fold: bool) -> MatchingEngine {
    let lo = MID - BAND_TICKS;
    let hi = MID + BAND_TICKS;
    let cfg = MarketConfig {
        market_id: 1,
        tick_size: Price(TICK),
        lot_size: Qty(LOT),
        min_price: to_price(lo),
        max_price: to_price(hi),
        max_resting: (max_orders as u32).min(trading::MAX_RESTING_LIMIT),
    };
    let mut e = MatchingEngine::new(
        cfg.validated().unwrap(),
        DenseBook::new(cfg.validated().unwrap()).unwrap(),
    )
    .unwrap();
    if fold {
        e.enable_resting_fold(exchange::book_resting_leaf);
    }
    e
}

/// Resolve corpus commands to engine ops (untimed) while executing
/// them, so the engine ends in the post-state of the stream.
struct Resolver {
    native: bool,
    /// `--digest`: FNV-1a over every fill's `(tick, qty-in-lots)` plus the count.
    digest: u64,
    trades: u64,
    /// corpus id -> (engine id, side, order type) of a live resting order.
    live: Vec<Option<(OrderId, Side, OrderType, TimeInForce)>>,
}

impl Resolver {
    fn run(
        &mut self,
        e: &mut MatchingEngine,
        cmds: &[Cmd],
        fills: &mut Vec<trading::FillEvent>,
    ) -> Vec<Op> {
        let mut ops = Vec::with_capacity(cmds.len());
        for c in cmds {
            fills.clear();
            match c {
                Cmd::New { id, order } => {
                    ops.push(Op::Place(*order));
                    let out = e.place(*order, fills).unwrap();
                    self.absorb(fills);
                    self.note(*id, order, out);
                }
                Cmd::Cancel { id } => {
                    let eid = self.live.get_mut(*id as usize).and_then(Option::take);
                    let oid = eid.map_or(OrderId(u64::MAX - 1), |t| t.0);
                    ops.push(Op::Cancel(oid));
                    let _ = e.cancel(oid);
                }
                Cmd::Replace { id, price, qty } => {
                    let Some(Some((oid, side, ot, tif))) = self.live.get(*id as usize).copied()
                    else {
                        ops.push(Op::Cancel(OrderId(u64::MAX - 1)));
                        continue;
                    };
                    let order = NewOrder {
                        side,
                        order_type: ot,
                        tif,
                        price: to_price(*price),
                        qty: Qty(*qty * LOT),
                        owner: Address([(*id % 251) as u8 + 1; 20]),
                        stp: StpMode::None,
                    };
                    if self.native {
                        ops.push(Op::Amend(oid, order.price, order.qty));
                        let out = e.amend(
                            oid,
                            order.price,
                            order.qty,
                            StpMode::None,
                            fills,
                            &mut trading::NoCap,
                        );
                        self.absorb(fills);
                        if matches!(out, Ok(trading::AmendOutcome::Filled)) {
                            self.live[*id as usize] = None;
                        }
                        continue;
                    }
                    self.live[*id as usize] = None;
                    ops.push(Op::Replace(oid, order));
                    let _ = e.cancel(oid);
                    let out = e.place(order, fills).unwrap();
                    self.absorb(fills);
                    self.note(*id, &order, out);
                }
            }
        }
        ops
    }

    fn absorb(&mut self, fills: &[trading::FillEvent]) {
        for f in fills {
            let tick = (f.price.0 - MIN_PRICE) / TICK + (MID - BAND_TICKS) as u64;
            for w in [tick, f.qty.0 / LOT] {
                self.digest = (self.digest ^ w).wrapping_mul(0x0100_0000_01B3);
            }
            self.trades += 1;
        }
    }

    fn note(&mut self, id: u64, order: &NewOrder, out: OrderOutcome) {
        if let OrderOutcome::Resting { order_id, .. } = out {
            let i = id as usize;
            if self.live.len() <= i {
                self.live.resize(i + 1, None);
            }
            self.live[i] = Some((order_id, order.side, order.order_type, order.tif));
        }
    }
}

/// Fill destination for the timed pass: the standard `Vec` sink, or a
/// counting sink (`--sink count`) that never materializes the events,
/// showing what a leaner sink buys.
trait Probe: FillSink {
    fn reset(&mut self);
    fn count(&self) -> u64;
}

impl Probe for Vec<trading::FillEvent> {
    #[inline(always)]
    fn reset(&mut self) {
        self.clear();
    }
    #[inline(always)]
    fn count(&self) -> u64 {
        self.len() as u64
    }
}

#[derive(Default)]
struct CountSink(u64);

impl FillSink for CountSink {
    #[inline(always)]
    fn fill(&mut self, f: trading::FillEvent) {
        self.0 = self.0.wrapping_add(f.qty.0);
    }
}

impl Probe for CountSink {
    #[inline(always)]
    fn reset(&mut self) {}
    #[inline(always)]
    fn count(&self) -> u64 {
        self.0
    }
}

#[inline(always)]
fn exec<S: Probe>(e: &mut MatchingEngine, op: &Op, fills: &mut S) -> u64 {
    fills.reset();
    match op {
        Op::Place(o) => {
            black_box(e.place_into(*o, fills).unwrap());
        }
        Op::Cancel(id) => {
            let _ = black_box(e.cancel(*id));
        }
        Op::Replace(id, o) => {
            let _ = black_box(e.cancel(*id));
            black_box(e.place_into(*o, fills).unwrap());
        }
        Op::Amend(id, p, q) => {
            let _ = black_box(e.amend(*id, *p, *q, StpMode::None, fills, &mut trading::NoCap));
        }
    }
    fills.count()
}

struct Ctx<'a> {
    max_orders: usize,
    fold: bool,
    block: usize,
    reps: usize,
    latency: bool,
    tag: &'a str,
    setup_ops: &'a [Op],
    run_ops: &'a [Op],
    /// `--batch`: the run phase as engine `Command`s for `apply_batch`.
    run_cmds: Option<&'a [trading::Command]>,
}

fn replay<S: Probe>(c: &Ctx<'_>, sink: &mut S, lat: Option<&mut Vec<u64>>) -> f64 {
    let mut e = make_engine(c.max_orders, c.fold);
    for op in c.setup_ops {
        exec(&mut e, op, sink);
    }
    let mut acc = 0u64;
    let t0 = Instant::now();
    let mut lat = lat;
    if let Some(cmds) = c.run_cmds {
        for chunk in cmds.chunks(c.block) {
            e.apply_batch(chunk, sink, |_, r| {
                black_box(&r);
            });
            if c.fold {
                e.settle_fold();
                acc = acc.wrapping_add(u64::from(e.resting_fold()[0]));
            }
        }
        let s = t0.elapsed().as_secs_f64();
        black_box(acc);
        return s;
    }
    for chunk in c.run_ops.chunks(c.block) {
        for op in chunk {
            if let Some(l) = lat.as_deref_mut() {
                let t = Instant::now();
                acc = acc.wrapping_add(exec(&mut e, op, sink));
                l.push(t.elapsed().as_nanos() as u64);
            } else {
                acc = acc.wrapping_add(exec(&mut e, op, sink));
            }
        }
        if c.fold {
            e.settle_fold();
            acc = acc.wrapping_add(u64::from(e.resting_fold()[0]));
        }
    }
    let s = t0.elapsed().as_secs_f64();
    black_box(acc);
    s
}

fn measure<S: Probe>(c: &Ctx<'_>, sink: &mut S, sink_name: &str) {
    let mode = if c.fold { "fold" } else { "nofold" };
    replay(c, sink, None); // warmup
    if c.latency {
        let mut l = Vec::with_capacity(c.run_ops.len());
        replay(c, sink, Some(&mut l));
        l.sort_unstable();
        println!(
            "| {} | {mode} | {sink_name} | latency | p50 {} | p99 {} | p99.9 {} | max {} |",
            c.tag,
            pct(&l, 0.5),
            pct(&l, 0.99),
            pct(&l, 0.999),
            l.last().unwrap()
        );
    } else {
        let mut t: Vec<f64> = (0..c.reps).map(|_| replay(c, sink, None)).collect();
        t.sort_by(f64::total_cmp);
        let n = c.run_ops.len() as f64;
        let med = t[t.len() / 2];
        println!(
            "| {} | {mode} | {sink_name} | {} | best {:.1}M/s | median {:.1}M/s | {:.1} ns/op |",
            c.tag,
            c.run_ops.len(),
            n / t[0] / 1e6,
            n / med / 1e6,
            1e9 * med / n
        );
    }
}

fn pct(sorted: &[u64], p: f64) -> u64 {
    sorted[(((sorted.len() - 1) as f64) * p).ceil() as usize]
}

fn main() {
    let args: Vec<String> = std::env::args().filter(|a| a != "--bench").collect();
    if args.get(1).map(String::as_str) == Some("--leaf") {
        // Probe: cost of one production leaf hash.
        let e = trading::RestingEntry {
            id: OrderId(7),
            side: Side::Buy,
            price: Price(1_000_000_000),
            qty: Qty(5_000),
            owner: Address([3; 20]),
        };
        let n = 5_000_000u64;
        let mut acc = 0u8;
        let t = Instant::now();
        for i in 0..n {
            let mut x = e;
            x.qty = Qty(i + 1);
            acc ^= exchange::book_resting_leaf(black_box(&x))[0];
        }
        black_box(acc);
        println!("leaf: {:.1} ns/call", t.elapsed().as_nanos() as f64 / n as f64);
        return;
    }
    let prefix = args.get(1).expect("usage: corpus <prefix> [--fold] [--reps R] [--latency]");
    let fold = args.iter().any(|a| a == "--fold");
    let latency = args.iter().any(|a| a == "--latency");
    let block: usize = args
        .iter()
        .position(|a| a == "--block")
        .and_then(|i| args.get(i + 1))
        .map_or(1024, |v| v.parse().unwrap());
    let reps: usize = args
        .iter()
        .position(|a| a == "--reps")
        .and_then(|i| args.get(i + 1))
        .map_or(5, |v| v.parse().unwrap());
    let (max_orders, setup) = load(&format!("{prefix}.setup.cmd.jsonl"));
    let (_, run) = load(&format!("{prefix}.run.cmd.jsonl"));
    let mut fills: Vec<trading::FillEvent> = Vec::with_capacity(4096);

    // Resolve pass (untimed): scratch engine learns each command's engine ids.
    let mut scratch = make_engine(max_orders, fold);
    let native = args.iter().any(|a| a == "--replace") && args.iter().any(|a| a == "native");
    let mut r = Resolver { native, digest: 0xCBF2_9CE4_8422_2325, trades: 0, live: Vec::new() };
    let setup_ops = r.run(&mut scratch, &setup, &mut fills);
    let run_ops = r.run(&mut scratch, &run, &mut fills);
    if args.iter().any(|a| a == "--digest") {
        // Final book in the matcher's canonical order: (side, tick) ascending,
        // FIFO within a level (the sort is stable).
        let mut es = Vec::new();
        scratch.resting_entries(&mut es);
        let mut book: Vec<(u8, u64, u64)> = es
            .iter()
            .map(|e| {
                let tick = (e.price.0 - MIN_PRICE) / TICK + (MID - BAND_TICKS) as u64;
                (u8::from(e.side == Side::Sell), tick, e.qty.0 / LOT)
            })
            .collect();
        book.sort_by_key(|&(s, t, _)| (s, t));
        let mut bd = 0xCBF2_9CE4_8422_2325u64;
        for (s, t, q) in &book {
            for w in [u64::from(*s), *t, *q] {
                bd = (bd ^ w).wrapping_mul(0x0100_0000_01B3);
            }
        }
        println!(
            "trades={} trade_digest={:016x} resting={} book_digest={bd:016x}",
            r.trades,
            r.digest,
            book.len()
        );
        return;
    }
    drop(scratch);

    let count_sink = args.iter().any(|a| a == "--sink") && args.iter().any(|a| a == "count");
    let batch = args.iter().any(|a| a == "--batch");
    let run_cmds: Vec<trading::Command> = run_ops
        .iter()
        .flat_map(|op| match *op {
            Op::Place(o) => vec![trading::Command::Place(o)],
            Op::Cancel(id) => vec![trading::Command::Cancel(id)],
            Op::Replace(id, o) => vec![trading::Command::Cancel(id), trading::Command::Place(o)],
            Op::Amend(id, price, qty) => {
                vec![trading::Command::Amend { id, price, qty, stp: StpMode::None }]
            }
        })
        .collect();
    let c = Ctx {
        run_cmds: batch.then_some(run_cmds.as_slice()),
        max_orders,
        fold,
        block,
        reps,
        latency,
        tag: prefix.rsplit('/').next().unwrap(),
        setup_ops: &setup_ops,
        run_ops: &run_ops,
    };
    if count_sink {
        measure(&c, &mut CountSink::default(), "count");
    } else {
        measure(&c, &mut fills, "vec");
    }
}
